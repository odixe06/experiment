"""Render experiments/README.md and experiments/<scenario>/README.md from experiments/scenarios.json + results.csv.

    python scripts/experiments_status.py           # write the READMEs
    python scripts/experiments_status.py --check   # exit 1 if a scenario misses a (method, seed) round-50 result

results.csv (one row per method/seed/view): method, seed, view, round, the ten metrics, status, source.
status: audited (CM -> 10 metrics checked), audited_f1 / marker_f1 (macro-F1 only in this repo), running, missing.
A cell counts as done only with a final-round f1_macro (round 50; CANPerFL 10 fine-tune epochs after FedAvg r50).
"""
import csv
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"
DONE = {"audited", "audited_f1", "marker_f1"}
MARK = {"audited": "", "audited_f1": "ᶠ", "marker_f1": "ᵐ"}


def load(scen):
    p = EXP / scen / "results.csv"
    return list(csv.DictReader(open(p, encoding="utf-8"))) if p.exists() else []


def final(r):
    return r["status"] in DONE and r["f1_macro"] and int(r["round"]) == (10 if r["method"] == "canperfl" else 50)


def cells(spec, rows, scen_cfg, hetero):
    out = {}
    for m in spec["methods"]:
        na = "na" in scen_cfg and (m == "centralized" or m not in hetero)
        for s in spec["seeds"]:
            rs = [r for r in rows if r["method"] == m and int(r["seed"]) == s]
            done = [r for r in rs if final(r)]
            if na:
                out[m, s] = ("n/a", None, None)
            elif done:
                out[m, s] = ("done", done[0], None)
            elif rs:
                out[m, s] = (rs[0]["status"], rs[0], rs[0]["round"])
            else:
                out[m, s] = ("missing", None, None)
    return out


def render(scen, cfg, spec):
    rows = load(scen)
    c = cells(spec, rows, cfg, spec["hetero"])
    L = [f"# {cfg['title']}", "", "<!-- generated by scripts/experiments_status.py from scenarios.json + results.csv; do not edit -->", "",
         f"- **Model:** {cfg['model']}", f"- **Code:** {cfg['code']}",
         "- **Protocol:** 5.343 xe nhận = 5.343 client, mọi client mỗi round, 1 epoch local trên fold train + val, 50 round, batch 64, "
         "AdamW cosine 1e-3 → 1e-5; centralized 50 epoch, batch 4.096. Headline = round 50 (CANPerFL: 10 epoch fine-tune sau FedAvg r50), "
         "view theo bài gốc. [protocol](../../docs/research/protocol.md)",
         "- **Tài liệu:** " + ", ".join(f"[{Path(d).stem}]({d})" for d in cfg["docs"])]
    if "na" in cfg:
        L.append(f"- **N/A:** {cfg['na']}")
    L += ["", "## Macro-F1 cuối (test toàn bộ 9.347.679 dòng)", "",
          "| Phương pháp | view | " + " | ".join(f"Seed {s}" for s in spec["seeds"]) + " | mean ± SD |", "|---|---|" + "---:|" * (len(spec["seeds"]) + 1)]
    for m in spec["methods"]:
        vals, txt, view = [], [], ""
        for s in spec["seeds"]:
            st, r, rnd = c[m, s]
            if r is not None:
                view = r["view"]
            if st == "done":
                vals.append(float(r["f1_macro"]))
                txt.append(f"{float(r['f1_macro']):.5f}{MARK[r['status']]}")
            elif st == "n/a":
                txt.append("N/A")
            elif st == "running":
                txt.append(f"chạy (r{rnd})")
            else:
                txt.append("thiếu")
        ms = f"{statistics.mean(vals):.5f} ± {statistics.stdev(vals):.5f}" if len(vals) >= 2 else (f"{vals[0]:.5f}" if vals else "")
        L.append(f"| {spec['names'][m]} | {view} | " + " | ".join(txt) + f" | {ms} |")
    L += ["", "Không dấu = CM → 10 metric đã audit (đủ 10 cột trong [results.csv](results.csv)); "
          "ᶠ = CM cuối đã audit nhưng repo chỉ giữ macro-F1; ᵐ = marker cuối Kaggle, chưa audit CM độc lập. "
          "SD = sample SD (ddof = 1)."]
    gaps = [(m, s, st) for (m, s), (st, _, _) in c.items() if st not in ("done", "n/a")]
    if gaps:
        L += ["", "## Còn thiếu", ""] + [f"- {spec['names'][m]} seed {s}: {st}" for m, s, st in gaps]
    comp = EXP / scen / "compute.csv"
    if comp.exists():
        L += ["", "## Compute", "", f"FLOP toàn bộ run (đếm op): [compute.csv](compute.csv); cách đo: [compute](../../docs/research/compute.md)."]
    (EXP / scen / "README.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return c


def main():
    spec = json.loads((EXP / "scenarios.json").read_text())
    allc, bad = {}, []
    for scen, cfg in spec["scenarios"].items():
        allc[scen] = render(scen, cfg, spec)
        bad += [(scen, m, s, st) for (m, s), (st, _, _) in allc[scen].items() if st not in ("done", "n/a")]
    L = ["# Experiments — mỗi thư mục một kịch bản", "", "<!-- generated by scripts/experiments_status.py; do not edit -->", "",
         "Mỗi kịch bản: `README.md` (sinh tự động), `results.csv` (method, seed, view, round, 10 metric, status, source), "
         "`compute.csv` khi đã đo. Cấu hình kịch bản: [scenarios.json](scenarios.json). Bảng gán xe → model của mixed: "
         "[mixed-model-v1](mixed-model-v1/). Tài liệu: [docs](../docs/README.md).", "",
         "Ô = số seed (41/42/43) đã có kết quả cuối; N/A = không áp dụng.", "",
         "| Kịch bản | " + " | ".join(spec["names"][m] for m in spec["methods"]) + " |", "|---|" + "---:|" * len(spec["methods"])]
    for scen, c in allc.items():
        cellv = []
        for m in spec["methods"]:
            sts = [c[m, s][0] for s in spec["seeds"]]
            cellv.append("N/A" if all(x == "n/a" for x in sts) else f"{sts.count('done')}/3" + ("+" if "running" in sts else ""))
        L.append(f"| [{scen}]({scen}/README.md) | " + " | ".join(cellv) + " |")
    L += ["", "`+` = còn seed đang chạy."]
    (EXP / "README.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    if "--check" in sys.argv:
        for b in bad:
            print(*b)
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
